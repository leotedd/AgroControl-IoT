-- PostgreSQL 17. Esquema paralelo; importar sólo en una base vacía autorizada.
-- Las acciones FK ejecutan triggers: retirar usuarios/dispositivos con órdenes mediante baja lógica.
SET TIME ZONE 'UTC';

CREATE TABLE usuarios (

  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  nombre           VARCHAR(100)     NOT NULL,
  email            VARCHAR(190)     NOT NULL,
  password_hash    VARCHAR(100)     NOT NULL,              -- bcrypt
  rol TEXT NOT NULL DEFAULT 'USUARIO',
  activo SMALLINT NOT NULL DEFAULT 1,
  intentos_fallidos INTEGER NOT NULL DEFAULT 0,
  bloqueado_hasta TIMESTAMPTZ(3) NULL,
  ultimo_acceso_en TIMESTAMPTZ(3) NULL,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT ck_enum_usuarios_rol CHECK (rol IN ('ADMIN','USUARIO')),
  CONSTRAINT ck_bool_usuarios_activo CHECK (activo IN (0,1)),
  CONSTRAINT ck_rango_usuarios_intentos_fallidos CHECK (intentos_fallidos BETWEEN 0 AND 65535)
);
CREATE UNIQUE INDEX uq_usuarios_email ON usuarios (lower(email));

CREATE TABLE tokens_refresco (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  usuario_id INTEGER NOT NULL,
  token_hash   CHAR(64)        NOT NULL,                    -- SHA-256 hex
  familia      CHAR(36)        NOT NULL,                    -- reutilización tras rotación ⇒ revocar familia
  expira_en TIMESTAMPTZ(3) NOT NULL,
  usado_en TIMESTAMPTZ(3) NULL,
  revocado_en TIMESTAMPTZ(3) NULL,
  user_agent   VARCHAR(255)    NULL,
  ip           VARCHAR(45)     NULL,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT fk_tokens_refresco_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uq_tokens_refresco_hash ON tokens_refresco (token_hash);
CREATE INDEX ix_tokens_refresco_usuario ON tokens_refresco (usuario_id);
CREATE INDEX ix_tokens_refresco_familia ON tokens_refresco (familia);

CREATE TABLE terrenos (

  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  nombre         VARCHAR(120)   NOT NULL,
  descripcion    VARCHAR(500)   NULL,
  ubicacion      VARCHAR(255)   NULL,
  latitud NUMERIC(9,6) NULL,
  longitud NUMERIC(9,6) NULL,
  area_m2 NUMERIC(12,2) NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  creado_por INTEGER NULL,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT fk_terrenos_creado_por FOREIGN KEY (creado_por) REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT ck_bool_terrenos_activo CHECK (activo IN (0,1))
);

CREATE TABLE usuario_terreno (

  usuario_id INTEGER NOT NULL,
  terreno_id INTEGER NOT NULL,
  rol TEXT NOT NULL,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (usuario_id, terreno_id),
  CONSTRAINT fk_ut_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
  CONSTRAINT fk_ut_terreno FOREIGN KEY (terreno_id) REFERENCES terrenos (id) ON DELETE CASCADE,
  CONSTRAINT ck_enum_usuario_terreno_rol CHECK (rol IN ('PROPIETARIO','OPERADOR','LECTOR'))
);
CREATE INDEX ix_usuario_terreno_terreno ON usuario_terreno (terreno_id);

CREATE TABLE cultivos (

  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  terreno_id INTEGER NOT NULL,
  nombre                   VARCHAR(120)  NOT NULL,
  variedad                 VARCHAR(120)  NULL,
  fecha_siembra            DATE          NULL,
  fecha_cosecha_estimada   DATE          NULL,
  humedad_objetivo_min_pct NUMERIC(4,1) NULL,              -- referencia agronómica (no se envía al ESP32)
  humedad_objetivo_max_pct NUMERIC(4,1) NULL,
  estado TEXT NOT NULL DEFAULT 'ACTIVO',
  notas                    TEXT          NULL,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT fk_cultivos_terreno FOREIGN KEY (terreno_id) REFERENCES terrenos (id) ON DELETE CASCADE,
  CONSTRAINT ck_enum_cultivos_estado CHECK (estado IN ('PLANIFICADO','ACTIVO','COSECHADO','CANCELADO'))
);
CREATE INDEX ix_cultivos_terreno ON cultivos (terreno_id);

CREATE TABLE zonas (

  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  terreno_id INTEGER NOT NULL,
  cultivo_id INTEGER NULL,
  nombre         VARCHAR(120)  NOT NULL,
  descripcion    VARCHAR(500)  NULL,
  area_m2 NUMERIC(12,2) NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT fk_zonas_terreno FOREIGN KEY (terreno_id) REFERENCES terrenos (id) ON DELETE CASCADE,
  CONSTRAINT fk_zonas_cultivo FOREIGN KEY (cultivo_id) REFERENCES cultivos (id) ON DELETE SET NULL,
  CONSTRAINT ck_bool_zonas_activo CHECK (activo IN (0,1))
);
CREATE INDEX ix_zonas_terreno ON zonas (terreno_id);
CREATE INDEX ix_zonas_cultivo ON zonas (cultivo_id);

CREATE TABLE dispositivos (

  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  terreno_id INTEGER NOT NULL,
  uid                      VARCHAR(40)       NOT NULL,      -- AGC-ESP32-0001
  nombre                   VARCHAR(120)      NOT NULL,
  modelo                   VARCHAR(60)       NOT NULL DEFAULT 'ESP32',
  estado TEXT NOT NULL DEFAULT 'ACTIVO',
  -- Credenciales (sólo hashes SHA-256 hex)
  token_hash               CHAR(64)          NULL,          -- NULL = revocado
  token_prefijo            VARCHAR(16)       NULL,
  token_creado_en TIMESTAMPTZ(3) NULL,
  token_anterior_hash      CHAR(64)          NULL,          -- válido durante el periodo de gracia
  token_anterior_expira_en TIMESTAMPTZ(3) NULL,
  -- Configuración deseada a nivel de dispositivo
  intervalo_telemetria_s INTEGER NOT NULL DEFAULT 10,
  intervalo_ordenes_s INTEGER NOT NULL DEFAULT 3,
  config_version_deseada BIGINT NOT NULL DEFAULT 1,  -- sólo crece
  config_version_aplicada BIGINT NOT NULL DEFAULT 0,
  config_aplicada_en TIMESTAMPTZ(3) NULL,
  config_rechazada_version BIGINT NULL,
  config_rechazo_errores JSONB NULL,
  -- Último estado reportado (snapshot)
  ultima_conexion_en TIMESTAMPTZ(3) NULL,
  ultima_ip                VARCHAR(45)       NULL,
  ip_local                 VARCHAR(45)       NULL,
  rssi_dbm                 SMALLINT          NULL,
  version_firmware         VARCHAR(16)       NULL,
  version_contrato         VARCHAR(16)       NULL,
  id_arranque_actual       CHAR(8)           NULL,
  uptime_ms BIGINT NULL,
  arranque_detectado_en TIMESTAMPTZ(3) NULL,
  hardware_confirmado SMALLINT NULL,
  tope_riego_s INTEGER NULL,          -- TOPE_ABSOLUTO_RIEGO_S compilado (≤ 600)
  max_id_orden_procesada BIGINT NULL,
  reloj_confiable SMALLINT NULL,
  persistencia_ok SMALLINT NULL,
  tls_vigencia             VARCHAR(16)       NULL,          -- MBEDTLS | VERIFICADOR (contrato 4.1)
  diagnostico JSONB NULL,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT fk_dispositivos_terreno FOREIGN KEY (terreno_id) REFERENCES terrenos (id) ON DELETE RESTRICT,
  CONSTRAINT ck_dispositivos_intervalos CHECK (intervalo_telemetria_s BETWEEN 5 AND 3600
                                              AND intervalo_ordenes_s BETWEEN 2 AND 60),
  CONSTRAINT ck_dispositivos_tope CHECK (tope_riego_s IS NULL OR tope_riego_s BETWEEN 1 AND 600),
  CONSTRAINT ck_enum_dispositivos_estado CHECK (estado IN ('ACTIVO','DESHABILITADO')),
  CONSTRAINT ck_rango_dispositivos_intervalo_telemetria_s CHECK (intervalo_telemetria_s BETWEEN 0 AND 65535),
  CONSTRAINT ck_rango_dispositivos_intervalo_ordenes_s CHECK (intervalo_ordenes_s BETWEEN 0 AND 65535),
  CONSTRAINT ck_rango_dispositivos_config_version_deseada CHECK (config_version_deseada BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_rango_dispositivos_config_version_aplicada CHECK (config_version_aplicada BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_rango_dispositivos_config_rechazada_version CHECK (config_rechazada_version BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_rango_dispositivos_uptime_ms CHECK (uptime_ms >= 0),
  CONSTRAINT ck_bool_dispositivos_hardware_confirmado CHECK (hardware_confirmado IN (0,1)),
  CONSTRAINT ck_rango_dispositivos_tope_riego_s CHECK (tope_riego_s BETWEEN 0 AND 65535),
  CONSTRAINT ck_rango_dispositivos_max_id_orden_procesada CHECK (max_id_orden_procesada >= 0),
  CONSTRAINT ck_bool_dispositivos_reloj_confiable CHECK (reloj_confiable IN (0,1)),
  CONSTRAINT ck_bool_dispositivos_persistencia_ok CHECK (persistencia_ok IN (0,1))
);
CREATE UNIQUE INDEX uq_dispositivos_uid ON dispositivos (uid);
CREATE UNIQUE INDEX uq_dispositivos_token ON dispositivos (token_hash);
CREATE UNIQUE INDEX uq_dispositivos_token_anterior ON dispositivos (token_anterior_hash);
CREATE INDEX ix_dispositivos_terreno ON dispositivos (terreno_id);

CREATE TABLE sensores (

  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  dispositivo_id INTEGER NOT NULL,
  zona_id INTEGER NULL,
  codigo                 VARCHAR(16)       NOT NULL,
  tipo TEXT NOT NULL,
  modelo                 VARCHAR(60)       NULL,            -- "Capacitivo D43"
  unidad                 VARCHAR(10)       NOT NULL DEFAULT '%',
  -- Calibración (valores de BANCO por defecto; no agronómicos)
  raw_seco INTEGER NOT NULL DEFAULT 3000,
  raw_humedo INTEGER NOT NULL DEFAULT 1300,
  calibracion_confirmada SMALLINT NOT NULL DEFAULT 0,
  calibrado_por INTEGER NULL,
  calibrado_en TIMESTAMPTZ(3) NULL,
  -- Última lectura (snapshot)
  ultimo_valor NUMERIC(4,1) NULL,
  ultimo_raw INTEGER NULL,
  ultimo_estado          VARCHAR(20)       NULL,            -- reportado
  ultima_lectura_en TIMESTAMPTZ(3) NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT fk_sensores_dispositivo FOREIGN KEY (dispositivo_id) REFERENCES dispositivos (id) ON DELETE CASCADE,
  CONSTRAINT fk_sensores_zona FOREIGN KEY (zona_id) REFERENCES zonas (id) ON DELETE SET NULL,
  CONSTRAINT fk_sensores_calibrado_por FOREIGN KEY (calibrado_por) REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT ck_sensores_calibracion CHECK (raw_seco BETWEEN 21 AND 4074
                                            AND raw_humedo BETWEEN 21 AND 4074
                                            AND ABS(raw_seco - raw_humedo) >= 200),
  CONSTRAINT ck_enum_sensores_tipo CHECK (tipo IN ('HUMEDAD_SUELO','TEMPERATURA_AMBIENTE','HUMEDAD_AMBIENTE','NIVEL_TANQUE','CAUDAL')),
  CONSTRAINT ck_rango_sensores_raw_seco CHECK (raw_seco BETWEEN 0 AND 65535),
  CONSTRAINT ck_rango_sensores_raw_humedo CHECK (raw_humedo BETWEEN 0 AND 65535),
  CONSTRAINT ck_bool_sensores_calibracion_confirmada CHECK (calibracion_confirmada IN (0,1)),
  CONSTRAINT ck_rango_sensores_ultimo_raw CHECK (ultimo_raw BETWEEN 0 AND 65535),
  CONSTRAINT ck_bool_sensores_activo CHECK (activo IN (0,1))
);
CREATE UNIQUE INDEX uq_sensores_dispositivo_codigo ON sensores (dispositivo_id, codigo);
CREATE INDEX ix_sensores_zona ON sensores (zona_id);

CREATE TABLE actuadores (

  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  dispositivo_id INTEGER NOT NULL,
  zona_id INTEGER NULL,
  codigo                     VARCHAR(16)      NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'BOMBA',
  descripcion                VARCHAR(255)     NULL,
  -- Estado reportado por el ESP32 (snapshot). VARCHAR: valores reportados.
  modo_reportado             VARCHAR(20)      NULL,         -- DESHABILITADO | MANUAL | AUTOMATICO
  estado_bomba               VARCHAR(20)      NULL,         -- APAGADA | RIEGO_MANUAL | RIEGO_AUTOMATICO
  riego_transcurrido_s BIGINT NULL,
  riego_restante_s BIGINT NULL,
  descanso_restante_s BIGINT NULL,
  bloqueo_id BIGINT NULL,         -- id_bloqueo reportado (contrato 10.5)
  bloqueo_tipo               VARCHAR(20)      NULL,         -- CRITICO | PREVENTIVO | NULL
  bloqueo_causa              VARCHAR(40)      NULL,
  bloqueo_liberable_remoto SMALLINT NULL,
  -- Instante de activación del bloqueo (contrato 7, estado_actuador). desde_uptime_ms pertenece SIEMPRE
  -- a bloqueo_desde_id_arranque, no al arranque actual: nunca restarlo de un uptime de otro arranque.
  bloqueo_desde_id_arranque  CHAR(8)          NULL,
  bloqueo_desde_uptime_ms BIGINT NULL,
  bloqueo_desde_ts TIMESTAMPTZ(3) NULL,         -- UTC del dispositivo si su reloj era confiable
  rearmes_remotos_episodio SMALLINT NULL,         -- 0/1, común a toda causa PREVENTIVO (contrato 10.5)
  id_orden_activa BIGINT NULL,
  -- Orden temporal del snapshot: se descarta un estado con (arranque, uptime) anterior
  reportado_id_arranque      CHAR(8)          NULL,
  reportado_uptime_ms BIGINT NULL,
  reportado_en TIMESTAMPTZ(3) NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  creado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT fk_actuadores_dispositivo FOREIGN KEY (dispositivo_id) REFERENCES dispositivos (id) ON DELETE CASCADE,
  CONSTRAINT fk_actuadores_zona FOREIGN KEY (zona_id) REFERENCES zonas (id) ON DELETE SET NULL,
  CONSTRAINT ck_enum_actuadores_tipo CHECK (tipo IN ('BOMBA','VALVULA')),
  CONSTRAINT ck_rango_actuadores_riego_transcurrido_s CHECK (riego_transcurrido_s BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_rango_actuadores_riego_restante_s CHECK (riego_restante_s BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_rango_actuadores_descanso_restante_s CHECK (descanso_restante_s BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_rango_actuadores_bloqueo_id CHECK (bloqueo_id >= 0),
  CONSTRAINT ck_bool_actuadores_bloqueo_liberable_remoto CHECK (bloqueo_liberable_remoto IN (0,1)),
  CONSTRAINT ck_rango_actuadores_bloqueo_desde_uptime_ms CHECK (bloqueo_desde_uptime_ms >= 0),
  CONSTRAINT ck_rango_actuadores_rearmes_remotos_episodio CHECK (rearmes_remotos_episodio BETWEEN 0 AND 255),
  CONSTRAINT ck_rango_actuadores_id_orden_activa CHECK (id_orden_activa >= 0),
  CONSTRAINT ck_rango_actuadores_reportado_uptime_ms CHECK (reportado_uptime_ms >= 0),
  CONSTRAINT ck_bool_actuadores_activo CHECK (activo IN (0,1))
);
CREATE UNIQUE INDEX uq_actuadores_dispositivo_codigo ON actuadores (dispositivo_id, codigo);
CREATE INDEX ix_actuadores_zona ON actuadores (zona_id);

CREATE TABLE configuraciones_control (

  actuador_id INTEGER NOT NULL,
  sensor_id INTEGER NULL,
  modo TEXT NOT NULL DEFAULT 'DESHABILITADO',
  modo_origen TEXT NOT NULL DEFAULT 'USUARIO',
  modo_motivo        VARCHAR(40)       NULL,               -- p. ej. ORDEN_APAGAR, BLOQUEO, ARRANQUE, REARME
  umbral_inicio_pct NUMERIC(4,1) NOT NULL DEFAULT 30.0,
  umbral_parada_pct NUMERIC(4,1) NOT NULL DEFAULT 55.0,
  riego_max_s INTEGER NOT NULL DEFAULT 15,
  descanso_min_s BIGINT NOT NULL DEFAULT 60,
  actualizado_por INTEGER NULL,               -- NULL si origen SISTEMA
  actualizado_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  PRIMARY KEY (actuador_id),
  CONSTRAINT fk_cc_actuador FOREIGN KEY (actuador_id) REFERENCES actuadores (id) ON DELETE CASCADE,
  CONSTRAINT fk_cc_sensor   FOREIGN KEY (sensor_id)   REFERENCES sensores (id)   ON DELETE SET NULL,
  CONSTRAINT fk_cc_usuario  FOREIGN KEY (actualizado_por) REFERENCES usuarios (id) ON DELETE SET NULL,
  CONSTRAINT ck_cc_histeresis CHECK (umbral_parada_pct - umbral_inicio_pct >= 5),
  CONSTRAINT ck_cc_rangos CHECK (umbral_inicio_pct BETWEEN 0 AND 95
                                 AND umbral_parada_pct BETWEEN 5 AND 100
                                 AND riego_max_s BETWEEN 5 AND 600
                                 AND descanso_min_s BETWEEN 5 AND 86400),
  -- riego_max_s ≤ dispositivos.tope_riego_s se valida en la aplicación (dato reportado).
  CONSTRAINT ck_enum_configuraciones_control_modo CHECK (modo IN ('DESHABILITADO','MANUAL','AUTOMATICO')),
  CONSTRAINT ck_enum_configuraciones_control_modo_origen CHECK (modo_origen IN ('USUARIO','SISTEMA')),
  CONSTRAINT ck_rango_configuraciones_control_riego_max_s CHECK (riego_max_s BETWEEN 0 AND 65535),
  CONSTRAINT ck_rango_configuraciones_control_descanso_min_s CHECK (descanso_min_s BETWEEN 0 AND 4294967295)
);
CREATE INDEX ix_cc_sensor ON configuraciones_control (sensor_id);

CREATE TABLE mediciones (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
