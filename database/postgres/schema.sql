CREATE FUNCTION fn_ordenes_inmutables() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- (a) Identidad y contenido: nunca cambian tras el INSERT (incluido el id).
  IF NOT (OLD.id              IS NOT DISTINCT FROM NEW.id)
     OR NOT (OLD.dispositivo_id  IS NOT DISTINCT FROM NEW.dispositivo_id)
     OR NOT (OLD.actuador_id     IS NOT DISTINCT FROM NEW.actuador_id)
     OR NOT (OLD.tipo            IS NOT DISTINCT FROM NEW.tipo)
     OR NOT (OLD.parametros      IS NOT DISTINCT FROM NEW.parametros)
     OR NOT (OLD.ttl_s           IS NOT DISTINCT FROM NEW.ttl_s)
     OR NOT (OLD.origen          IS NOT DISTINCT FROM NEW.origen)
     OR NOT (OLD.solicitada_por  IS NOT DISTINCT FROM NEW.solicitada_por)
     OR NOT (OLD.idempotency_key IS NOT DISTINCT FROM NEW.idempotency_key)
     OR NOT (OLD.creada_en       IS NOT DISTINCT FROM NEW.creada_en)
     OR NOT (OLD.expira_en       IS NOT DISTINCT FROM NEW.expira_en) THEN
    RAISE EXCEPTION 'ordenes_riego: campo de identidad o contenido inmutable' USING ERRCODE = 'P0001';
  END IF;

  -- (b) Escritura única: pueden pasar de NULL a un valor una sola vez.
  IF    (OLD.entregada_en         IS NOT NULL AND NOT (OLD.entregada_en         IS NOT DISTINCT FROM NEW.entregada_en))
     OR (OLD.id_arranque_entrega  IS NOT NULL AND NOT (OLD.id_arranque_entrega  IS NOT DISTINCT FROM NEW.id_arranque_entrega))
     OR (OLD.cancelada_en         IS NOT NULL AND NOT (OLD.cancelada_en         IS NOT DISTINCT FROM NEW.cancelada_en))
     OR (OLD.cancelada_por        IS NOT NULL AND NOT (OLD.cancelada_por        IS NOT DISTINCT FROM NEW.cancelada_por))
     OR (OLD.cerrada_por_orden_id IS NOT NULL AND NOT (OLD.cerrada_por_orden_id IS NOT DISTINCT FROM NEW.cerrada_por_orden_id))
     OR (OLD.motivo_cierre        IS NOT NULL AND NOT (OLD.motivo_cierre        IS NOT DISTINCT FROM NEW.motivo_cierre)) THEN
    RAISE EXCEPTION 'ordenes_riego: campo de escritura unica ya asignado' USING ERRCODE = 'P0001';
  END IF;

  -- (c) Estado final: no cambia (SIN_CONFIRMAR sí puede pasar a final).
  IF OLD.estado IN ('EJECUTADA','RECHAZADA','FALLIDA','EXPIRADA','CANCELADA')
     AND NOT (OLD.estado IS NOT DISTINCT FROM NEW.estado) THEN
    RAISE EXCEPTION 'ordenes_riego: estado final inmutable' USING ERRCODE = 'P0001';
  END IF;

  -- (d) ACK: una vez registrado el primer resultado no cambia ningún campo del ACK.
  IF OLD.resultado IS NOT NULL AND (
        NOT (OLD.resultado              IS NOT DISTINCT FROM NEW.resultado)
     OR NOT (OLD.codigo_motivo          IS NOT DISTINCT FROM NEW.codigo_motivo)
     OR NOT (OLD.mensaje                IS NOT DISTINCT FROM NEW.mensaje)
     OR NOT (OLD.duracion_aplicada_s    IS NOT DISTINCT FROM NEW.duracion_aplicada_s)
     OR NOT (OLD.ejecutada_en           IS NOT DISTINCT FROM NEW.ejecutada_en)
     OR NOT (OLD.confirmada_en          IS NOT DISTINCT FROM NEW.confirmada_en)
     OR NOT (OLD.confirmacion_tardia    IS NOT DISTINCT FROM NEW.confirmacion_tardia)
     OR NOT (OLD.ack_uptime_ms          IS NOT DISTINCT FROM NEW.ack_uptime_ms)
     OR NOT (OLD.ack_id_arranque_origen IS NOT DISTINCT FROM NEW.ack_id_arranque_origen)
     OR NOT (OLD.ack_id_arranque_envio  IS NOT DISTINCT FROM NEW.ack_id_arranque_envio)
     OR NOT (OLD.ack_config_version     IS NOT DISTINCT FROM NEW.ack_config_version)
     OR NOT (OLD.ack_cuerpo             IS NOT DISTINCT FROM NEW.ack_cuerpo)) THEN
    RAISE EXCEPTION 'ordenes_riego: ACK inmutable' USING ERRCODE = 'P0001';
  END IF;

  -- (e) Contadores: sólo crecen.
  IF NEW.ack_conflictos < OLD.ack_conflictos OR NEW.intentos_entrega < OLD.intentos_entrega THEN
    RAISE EXCEPTION 'ordenes_riego: contador decreciente' USING ERRCODE = 'P0001';
  END IF;

  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_ordenes_inmutables BEFORE UPDATE ON ordenes_riego FOR EACH ROW EXECUTE FUNCTION fn_ordenes_inmutables();

