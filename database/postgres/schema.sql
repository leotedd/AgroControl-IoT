  seq BIGINT NOT NULL,
  uptime_ms BIGINT NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_mediciones_sensor FOREIGN KEY (sensor_id) REFERENCES sensores (id) ON DELETE CASCADE,
  CONSTRAINT ck_rango_mediciones_valor_raw CHECK (valor_raw BETWEEN 0 AND 65535),
  CONSTRAINT ck_bool_mediciones_hora_estimada CHECK (hora_estimada IN (0,1)),
  CONSTRAINT ck_rango_mediciones_seq CHECK (seq BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_rango_mediciones_uptime_ms CHECK (uptime_ms >= 0)
);
CREATE UNIQUE INDEX uq_mediciones_dedup ON mediciones (sensor_id, id_arranque, seq);
CREATE INDEX ix_mediciones_sensor_fecha ON mediciones (sensor_id, medido_en);

