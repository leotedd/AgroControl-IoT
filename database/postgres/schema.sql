CREATE FUNCTION fn_tocar_actualizado_en() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD THEN NEW.actualizado_en := clock_timestamp(); END IF;
  RETURN NEW;
END;
$$;

