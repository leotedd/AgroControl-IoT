CREATE TABLE ordenes_riego (

  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
  dispositivo_id INTEGER NOT NULL,
  actuador_id INTEGER NOT NULL,
  tipo TEXT NOT NULL,
  parametros JSONB NOT NULL,         -- inmutable (duracion_s solicitada)
  ttl_s INTEGER NOT NULL,
  estado TEXT NOT NULL DEFAULT 'PENDIENTE',
  origen TEXT NOT NULL DEFAULT 'WEB',
  solicitada_por INTEGER NULL,
  idempotency_key       VARCHAR(64)       NULL,
  -- RESTABLECER_BLOQUEO: parametros = { id_bloqueo, causa, inspeccion_confirmada } (contrato 10.5);
  -- el usuario que confirmó la inspección es solicitada_por y queda en auditoria.
  creada_en TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  expira_en TIMESTAMPTZ(3) NOT NULL,
  -- Entrega
  entregada_en TIMESTAMPTZ(3) NULL,             -- primera entrega
  ultima_entrega_en TIMESTAMPTZ(3) NULL,
  intentos_entrega INTEGER NOT NULL DEFAULT 0,
  id_arranque_entrega   CHAR(8)           NULL,
  -- Cierre sin ACK
  cancelada_en TIMESTAMPTZ(3) NULL,
  cancelada_por INTEGER NULL,
  motivo_cierre         VARCHAR(40)       NULL,             -- REEMPLAZADA, REEMPLAZADA_POR_APAGAR, REINICIO_DISPOSITIVO, SIN_ACK…
  cerrada_por_orden_id BIGINT NULL,             -- orden que la reemplazó
  -- ACK inmutable (primer ACK válido)
  confirmada_en TIMESTAMPTZ(3) NULL,             -- hora del servidor al recibir el ACK
  confirmacion_tardia SMALLINT NOT NULL DEFAULT 0,
  resultado             VARCHAR(20)       NULL,             -- EJECUTADA | RECHAZADA | FALLIDA
  codigo_motivo         VARCHAR(40)       NULL,
  mensaje               VARCHAR(200)      NULL,
  duracion_aplicada_s INTEGER NULL,
  ejecutada_en TIMESTAMPTZ(3) NULL,             -- hora informada por el dispositivo
  ack_uptime_ms BIGINT NULL,             -- del arranque ack_id_arranque_origen
  ack_id_arranque_origen CHAR(8)          NULL,             -- arranque en que se generó el ACK (contrato 7.3)
  ack_id_arranque_envio CHAR(8)           NULL,             -- X-Id-Arranque con que llegó (puede ser posterior)
  ack_config_version BIGINT NULL,             -- informativo; no reconcilia
  ack_cuerpo JSONB NULL,             -- cuerpo completo del primer ACK
  ack_conflictos INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  CONSTRAINT fk_ordenes_dispositivo FOREIGN KEY (dispositivo_id) REFERENCES dispositivos (id) ON DELETE CASCADE,
